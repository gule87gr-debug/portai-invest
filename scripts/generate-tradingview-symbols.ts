/**
 * Regenerates src/lib/stockDatabase/tradingViewSymbols.generated.ts.
 * Run: bun scripts/generate-tradingview-symbols.ts
 *
 * Sources (public symbol directories only — no prices are fetched):
 *  - Nasdaq Trader symbol directory (nasdaqlisted.txt / otherlisted.txt)
 *  - Binance spot exchange info (symbol list) and Coinbase Exchange products
 * Writes the unmapped tickers to tradingview-unmapped.csv in the working dir.
 */
import { writeFileSync } from "fs";
import { assetDatabase } from "../src/lib/stockDatabase/index";

const text = async (url: string) => (await fetch(url, { headers: { "User-Agent": "portai-symbol-map" } })).text();

const [nasdaq, other, binance, coinbase] = await Promise.all([
  text("https://www.nasdaqtrader.com/dynamic/SymDir/nasdaqlisted.txt"),
  text("https://www.nasdaqtrader.com/dynamic/SymDir/otherlisted.txt"),
  text("https://data-api.binance.vision/api/v3/exchangeInfo?permissions=SPOT").then(JSON.parse),
  text("https://api.exchange.coinbase.com/products").then(JSON.parse),
]);

// otherlisted exchange codes → TradingView prefixes (NYSE Arca trades under AMEX on TradingView).
const OTHER_EXCHANGE: Record<string, string> = { N: "NYSE", A: "AMEX", P: "AMEX", Z: "CBOE" };
const us = new Map<string, string>();
for (const line of nasdaq.split("\n").slice(1)) {
  const [sym, , , test] = line.split("|");
  if (sym && test === "N" && !sym.startsWith("File Creation")) us.set(sym, "NASDAQ");
}
for (const line of other.split("\n").slice(1)) {
  const [sym, , exch, , , , test] = line.split("|");
  if (sym && test === "N" && OTHER_EXCHANGE[exch]) us.set(sym, OTHER_EXCHANGE[exch]);
}

const binanceUsdt = new Set<string>(
  binance.symbols.filter((s: any) => s.status === "TRADING" && s.quoteAsset === "USDT").map((s: any) => s.baseAsset),
);
const coinbaseUsd = new Set<string>(
  coinbase.filter((p: any) => p.quote_currency === "USD" && p.status === "online" && !p.trading_disabled).map((p: any) => p.base_currency),
);

const usOut: Record<string, string[]> = { NASDAQ: [], NYSE: [], AMEX: [], CBOE: [] };
const cryptoOut: string[] = [];
for (const a of assetDatabase) {
  const t = a.ticker.toUpperCase();
  if (a.type === "crypto") {
    const base = t.replace(/-USD$/, "").replace(/USDT$/, "").replace(/USD$/, "");
    if (base === t || !/^[A-Z0-9]+$/.test(base)) continue;
    if (binanceUsdt.has(base)) cryptoOut.push(`${t}=BINANCE:${base}USDT`);
    else if (coinbaseUsd.has(base)) cryptoOut.push(`${t}=COINBASE:${base}USD`);
    continue;
  }
  const ex = us.get(t);
  if (ex) usOut[ex].push(t);
}

const body = `// AUTO-GENERATED by scripts/generate-tradingview-symbols.ts on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
// US tickers grouped by their primary listing exchange (TradingView prefix).
export const US_LISTINGS: Record<string, string> = {
${Object.entries(usOut).map(([k, v]) => `  ${k}: ${JSON.stringify(v.join(" "))},`).join("\n")}
};
// Crypto tickers → TradingView pair (Binance USDT first, then Coinbase USD).
export const CRYPTO_SYMBOLS = ${JSON.stringify(cryptoOut.join(" "))};
`;
writeFileSync("src/lib/stockDatabase/tradingViewSymbols.generated.ts", body);

const { toTradingViewSymbol } = await import("../src/lib/stockDatabase/tradingView");
const unmapped = assetDatabase.filter((a) => !toTradingViewSymbol(a.ticker));
writeFileSync("tradingview-unmapped.csv", "ticker,name,type\n" + unmapped.map((a) => [a.ticker, `"${a.name.replace(/"/g, "'")}"`, a.type].join(",")).join("\n") + "\n");
console.log(`assets=${assetDatabase.length} mapped=${assetDatabase.length - unmapped.length} unmapped=${unmapped.length}`);
